<?php

namespace App\Entity;

use App\Repository\RoleRepository;
use Doctrine\ORM\Mapping as ORM;

#[ORM\Entity(repositoryClass: RoleRepository::class)]
class Role
{
    #[ORM\Id]
    #[ORM\GeneratedValue]
    #[ORM\Column]
    private ?int $id = null;

    // nom: VARCHAR(255) NOT NULL UNIQUE ('ROLE_ADMIN', 'ROLE_EMPLOYE', 'ROLE_UTILISATEUR')
    #[ORM\Column(length: 255, unique: true)] // unique: true = deux rôles ne peuvent pas avoir le même nom
    private ?string $nom = null;

    public function getId(): ?int
    {
        return $this->id;
    }

    public function getNom(): ?string
    {
        return $this->nom;
    }

    public function setNom(string $nom): static
    {
        $this->nom = $nom;

        return $this;
    }
}
